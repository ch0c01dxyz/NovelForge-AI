async function seedUser(
  email: string,
  platformRole: "SUPER_ADMIN" | null = null,
): Promise<{ userId: string; cookie: string }> {
  const user = await db.user.create({
    data: {
      email,
      passwordHash: "x",
      displayName: email,
      platformRole: platformRole ?? undefined,
    },
  });
  const token = generateSessionToken();
  await db.session.create({
    data: {
      tokenHash: hashSessionToken(token),
      userId: user.id,
      expiresAt: new Date(Date.now() + 3600_000),
    },
  });
  return { userId: user.id, cookie: `${SESSION_COOKIE}=${token}` };
}

async function seedWorkspace(ownerId: string, slug: string) {
  const ws = await db.workspace.create({
    data: { name: slug, slug, ownerId },
  });
  await db.membership.create({
    data: { workspaceId: ws.id, userId: ownerId, role: "OWNER" },
  });
  const novel = await db.novel.create({
    data: {
      workspaceId: ws.id,
      title: `Novel ${slug}`,
      slug,
      createdById: ownerId,
    },
  });
  return { workspaceId: ws.id, novelId: novel.id };
}

/** Register a gateway through the API as an admin; returns its id. */
async function createGateway(
  cookie: string,
  name: string,
  extra: Record<string, unknown> = {},
) {
  const res = await app.inject({
    method: "POST",
    url: "/api/gateways",
    headers: { cookie },
    payload: {
      name,
      baseUrl: "http://localhost:20128",
      apiKey: `sk-secret-${name}`,
      ...extra,
    },
  });
  expect(res.statusCode).toBe(201);
  return (res.json() as { id: string }).id;
}

/** Map a discovered model to a profile, end to end through the API. */
async function mapProfile(
  cookie: string,
  gatewayId: string,
  profile: string,
  modelId = "fake-writer",
) {
  const sync = await app.inject({
    method: "POST",
    url: `/api/gateways/${gatewayId}/sync-models`,
    headers: { cookie },
  });
  expect(sync.statusCode).toBe(200);
  const models = await app.inject({
    method: "GET",
    url: "/api/models",
    headers: { cookie },
  });
  const row = (models.json() as Array<{ id: string; modelId: string; gatewayId: string }>).find(
    (m) => m.modelId === modelId && m.gatewayId === gatewayId,
  );
  expect(row).toBeDefined();
  const put = await app.inject({
    method: "PUT",
    url: "/api/model-profiles",
    headers: { cookie },
    payload: { profile, modelId: row!.id },
  });
  expect(put.statusCode).toBe(200);
  return row!.id;
}

