-- Phase 6 — evidence FK hardening.
--
-- Split out of 20260929_phase6_story_intelligence after that migration had
-- already been committed. The three changes below were originally edits made
-- in place to the Phase 6 migration. That is only safe while a migration is
-- unreleased: Prisma records a migration as applied by its CHECKSUM, so
-- editing one that has run anywhere makes every deployed database disagree
-- with the repository and `migrate deploy` refuse to proceed. Splitting them
-- into their own migration makes the Phase 6 migration immutable again and
-- leaves a database that already applied the edited form only one migration
-- behind, which is a normal deploy rather than a baseline reset.
--
-- It does NOT make the changes re-runnable. Measured, not assumed: replaying
-- this file against an already-hardened database succeeds for the DROP/ADD
-- pairs but FAILS on CREATE INDEX with a duplicate-index error, because the
-- drop half recreates the index under the same name. The migration is
-- idempotent in the sense that matters for a deploy — the end state is
-- identical however the change arrived — not in the sense that it can be run
-- twice. Any manual re-run needs the index statement skipped.
--
--   1. canon_fact_sources.chapter_version_id — CASCADE became RESTRICT.
--      A citation is the only place a fact's span is stored, so cascading one
--      away leaves the fact claiming support it can no longer show.
--      chapter_versions already cascades from chapters, and deleteChapter
--      (services/manuscript.ts) hard-deletes any non-PUBLISHED chapter — so
--      CASCADE let a routine draft deletion silently strip canon evidence
--      with nothing canon-side recording why. Deleting a cited chapter is now
--      refused instead, and the refusal is escapable:
--      DELETE .../canon/facts/:factId/sources/:sourceId unlinks the evidence.
--
--   2. canon_fact_sources.reference_version_id — CASCADE became RESTRICT for
--      the same reason: a reference revision is a pinned citation, not a
--      disposable child of the fact.
--
--   3. canon_proposals.object_entity_id — the FK was missing entirely. The
--      column was a bare uuid, so a proposal could name an entity that does
--      not exist, or belongs to another novel, and approveProposal copies it
--      verbatim into canon_facts.object_entity_id, which IS constrained. The
--      failure therefore surfaced at approval time, far from the write that
--      caused it. CASCADE matches its sibling subject column on this table.
--      The index is added with it: the referencing side is scanned when the
--      parent row is deleted, and without it every story-entity delete
--      seq-scans canon_proposals.
--
-- Every statement below was generated by `prisma migrate diff` from the
-- migrations directory to schema.prisma, not hand-written, so the drift check
-- is the proof that this migration and the schema agree.

