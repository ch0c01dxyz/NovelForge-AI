/**
 * Fake gateway behaviour keyed by gateway NAME (records carry names).
 * A name absent from `behaviour` succeeds.
 */
type Behaviour = Record<
  string,
  {
    ok: boolean;
    category?: string;
    partial?: boolean;
    content?: string;
    /** Gateway's generateStream never resolves — models a live upstream. */
    hang?: boolean;
  }
>;
let behaviour: Behaviour = {};

/** Every `signal` the fake gateways' generateStream received, in order. */
const seenSignals: Array<AbortSignal | null> = [];
const seenTextMessages: GenerateRequest["messages"][] = [];
const seenBuffered: boolean[] = [];

function fakeGateway(rec: GatewayRecord): AIGateway {
  const b = behaviour[rec.name] ?? { ok: true };
  const fail = () => {
    throw new GatewayError(
      (b.category ?? "TRANSIENT") as
        | "TRANSIENT"
        | "RATE_LIMIT"
        | "AUTH"
        | "UNSUPPORTED"
        | "INVALID_REQUEST",
      "fake gateway failure",
      undefined,
      b.partial,
    );
  };
  return {
    id: rec.id,
    name: rec.name,
    async listModels() {
      // Honour the failure behaviour here too: model discovery is a
      // transport call and can fail like any other.
      if (!b.ok) fail();
      return [
        { modelId: "fake-writer", capabilities: ["chat"] },
        { modelId: "fake-embed", capabilities: ["embeddings"] },
      ];
    },
    async generate(req: GenerateRequest): Promise<GenerateResult> {
      seenBuffered.push(req.bufferStream === true);
      seenTextMessages.push(req.messages);
      if (!b.ok) fail();
      return {
        content: b.content ?? `generated by ${rec.name}`,
        model: `${rec.name}-model`,
        reportedModel: `${rec.name}-model`,
        inputTokens: 7,
        outputTokens: 11,
        finishReason: "stop",
      };
    },
    async *generateStream(req: GenerateRequest) {
      seenTextMessages.push(req.messages);
      // The route must hand its abort signal down so a client disconnect
      // reaches the transport (withTimeout combines it with the timeout).
      seenSignals.push(req.signal ?? null);
      if (!b.ok) {
        // Emit before failing so the manager/adapter see a partial stream.
        if (b.partial) {
          yield { delta: "", model: "partial-model", usage: { inputTokens: 5, outputTokens: 2 } };
          yield { delta: "partial " };
        }
        fail();
      }
      // A never-ending stream models a real upstream: it ends only if
      // someone fires the signal, the way a transport's fetch abort does.
      if (b.hang) {
        await new Promise((_resolve, reject) => {
          req.signal?.addEventListener("abort", () => reject(new Error("upstream aborted")), {
            once: true,
          });
        });
      }
      yield { delta: "streamed " };
      yield { delta: "text" };
      yield { delta: "", model: "stream-model", usage: { inputTokens: 7, outputTokens: 11 } };
    },
    async embed() {
      return { vectors: [[0.1, 0.2]], model: rec.name, inputTokens: 3 };
    },
    async healthCheck() {
      return b.ok
        ? { healthy: true, category: null }
        : { healthy: false, category: "TRANSIENT" as const };
    },
  };
}

